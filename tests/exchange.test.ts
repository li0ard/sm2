import { test, expect } from "bun:test";
import { hexToBytes } from "@noble/curves/utils.js";
import { keyExchangeA, keyExchangeB } from "../src";

const privA = hexToBytes("81EB26E941BB5AF16DF116495F90695272AE2CD63D6C4AE1678418BE48230029");
const pubA = hexToBytes("04160E12897DF4EDB61DD812FEB96748FBD3CCF4FFE26AA6F6DB9540AF49C942324A7DAD08BB9A459531694BEB20AA489D6649975E1BFCF8C4741B78B4B223007F");
const privB = hexToBytes("785129917D45A9EA5437A59356B82338EAADDA6CEB199088F14AE10DEFA229B5");
const pubB = hexToBytes("046AE848C57C53C7B1B5FA99EB2286AF078BA64C64591B8B566F7357D576F16DFBEE489D771621A27B36C5C7992062E9CD09A9264386F3FBEA54DFF69305621C4D");

const rpriA = hexToBytes("D4DE15474DB74D06491C440D305E012400990F3E390C7E87153C12DB2EA60BB3");
const rpubA = hexToBytes("0464CED1BDBC99D590049B434D0FD73428CF608A5DB8FE5CE07F15026940BAE40E376629C7AB21E7DB260922499DDB118F07CE8EAAE3E7720AFEF6A5CC062070C0");
const rpriB = hexToBytes("7E07124814B309489125EAED101113164EBF0F3458C5BD88335C1F9D596243D6");
const rpubB = hexToBytes("04ACC27688A6F7B706098BC91FF3AD1BFF7DC2802CDB14CCCCDB0A90471F9BD7072FEDAC0494B2FFC4D6853876C79B8F301C6573AD0AA50F39FC87181E1A1B46FE");

const expectedK = hexToBytes("6C89347354DE2484C60B4AB1FDE4C6E5");
const expectedS1 = hexToBytes("D3A0FE15DEE185CEAE907A6B595CC32A266ED7B3367E9983A896DC32FA20F8EB");
const expectedS2 = hexToBytes("18C7894B3816DF16CF07B05C5EC0BEF5D655D58F779CC1B400A4F3884644DB88");

test("Key exchange", () => {
    const resA = keyExchangeA(16, privA, pubB, rpriA, rpubB);
    const resB = keyExchangeB(16, privB, pubA, rpriB, rpubA);

    expect(resA.k).toStrictEqual(resB.k);
    expect(resA.k).toStrictEqual(expectedK);
    expect(resB.k).toStrictEqual(expectedK);

    expect(resA.S1).toStrictEqual(resB.S1);
    expect(resA.S1).toStrictEqual(expectedS1);
    expect(resB.S1).toStrictEqual(expectedS1);

    expect(resA.S2).toStrictEqual(resB.S2);
    expect(resA.S2).toStrictEqual(expectedS2);
    expect(resB.S2).toStrictEqual(expectedS2);
});